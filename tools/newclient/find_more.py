rev = json.loads((HERE / "tires-reviews.json").read_text(encoding="utf-8"))
def one(q):
    out = []
    for pg in range(1, 5):
        try:
            r = search("moscow", q, pg)
        except Exception:
            break
        if not r:
            break
        out += r; time.sleep(0.3)
    return out
n0 = len(ids)
with ThreadPoolExecutor(4) as ex:
    for res in ex.map(one, Q):
        for f in res:
            if re.search(r"шин|колёс|колес|tire|шиномонт", f["name"], re.I):
                ids.setdefault(f["id"], f)
new = [i for i in ids if i not in rev]
def rv(i):
    try: return i, reviews(i)
    except Exception as e: return i, {"err": str(e)}
with ThreadPoolExecutor(6) as ex:
    rev.update(dict(ex.map(rv, new)))
(HERE / "tires-ids.json").write_text(json.dumps(ids, ensure_ascii=False), encoding="utf-8")
(HERE / "tires-reviews.json").write_text(json.dumps(rev), encoding="utf-8")
print("запросов", len(Q), "было", n0, "стало", len(ids))
